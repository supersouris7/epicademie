/** Sens d'une notion (liste vide si aucun n'est écrit pour elle). */
const sensOf = (skillId: string): readonly Sens[] => {
  const cm = /^mcm[12]-(.+)$/.exec(skillId)?.[1];
  return (cm === undefined ? SIXIEME[skillId] : CM[cm]) ?? [];
};

/** Chapitres dont les notions portent leur sens (celles qui n'en ont pas restent inchangées). */
export const withSens = (chapters: readonly Chapter[]): readonly Chapter[] =>
  chapters.map((chapter) => ({
    ...chapter,
    skills: chapter.skills.map((skill) => {
      const sens = sensOf(skill.id);
      return sens.length > 0 ? { ...skill, sens } : skill;
    }),
  }));
